// Downloads open-source webfonts from Google Fonts and self-hosts them in public/fonts.
// Result: zero third-party requests at runtime, so the site can ship a strict CSP.
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'public', 'fonts')
await mkdir(outDir, { recursive: true })

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36'

const ALLOWED = new Set(['latin', 'latin-ext', 'arabic'])

const families = [
  { query: 'Poppins:wght@500;600;700', slug: 'poppins' },
  { query: 'Inter:wght@400;500;600;700', slug: 'inter' },
  { query: 'Cairo:wght@400;600;700', slug: 'cairo' },
]

const cssOut = ['/* Oneiria — self-hosted open-source webfonts (generated by tools/fetch-fonts.mjs). */']
let downloaded = 0

for (const fam of families) {
  const url = `https://fonts.googleapis.com/css2?family=${fam.query}&display=swap`
  const res = await fetch(url, { headers: { 'User-Agent': UA } })
  if (!res.ok) throw new Error(`${fam.slug}: CSS ${res.status}`)
  const css = await res.text()

  // Split into "/* subset */ @font-face { ... }" chunks
  const re = /\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g
  let m
  let idx = 0
  while ((m = re.exec(css)) !== null) {
    const subset = m[1]
    if (!ALLOWED.has(subset)) continue
    const block = m[2]

    const weight = (block.match(/font-weight:\s*([^;]+);/) || [, '400'])[1].trim()
    const style = (block.match(/font-style:\s*([^;]+);/) || [, 'normal'])[1].trim()
    if (style !== 'normal') continue

    const src = (block.match(/src:\s*url\(([^)]+)\)/) || [])[1]
    if (!src) continue

    const file = `${fam.slug}-${weight}-${subset}.woff2`
    const bin = await fetch(src, { headers: { 'User-Agent': UA } })
    if (!bin.ok) throw new Error(`${fam.slug}: font ${bin.status}`)
    await writeFile(join(outDir, file), Buffer.from(await bin.arrayBuffer()))
    downloaded++

    cssOut.push(
      block
        .replace(/src:\s*url\([^)]+\)/, `src: url("/fonts/${file}")`)
        .replace(/^@font-face\s*\{/, `@font-face {\n  /* ${fam.slug} ${weight} — ${subset} */`)
        .trim()
    )
    idx++
  }
  console.log(`${fam.slug}: ${idx} faces`)
}

await writeFile(join(outDir, 'fonts.css'), cssOut.join('\n\n') + '\n', 'utf8')
console.log(`downloaded ${downloaded} woff2 files -> public/fonts`)
